'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const directory = fs.existsSync(path.join(root, 'tests-v3')) ? 'tests-v3' : 'tests';
const files = fs.readdirSync(path.join(root, directory)).filter(name => name.endsWith('.test.cjs')).sort().map(name => path.join(directory, name));
const result = spawnSync(process.execPath, ['--test', ...(process.platform === 'win32' ? ['--test-concurrency=2'] : []), ...files], { cwd: root, stdio: 'inherit' });
if (result.error) console.error(result.error.message);
process.exit(result.status ?? 1);
